    error_type  VARCHAR2(100),
    message     VARCHAR2(500),
    emp_id      NUMBER,
    created_by  VARCHAR2(50) DEFAULT USER,
    create_at   TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

BEGIN
DBMS_OUTPUT.PUT_LINE('HUN: Üres error_log tábla létrehozva!');
DBMS_OUTPUT.PUT_LINE('ENG: Empty error_log table created!');
END;

